"""Central Facts Registry for ChaosRL.

Records every empirical number generated during execution to results/facts.json
and generates docs/FACTS.md. Ensures zero hardcoding in documentation.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional


RESULTS_DIR = Path("results")
FACTS_FILE = RESULTS_DIR / "facts.json"
DOCS_DIR = Path("docs")
FACTS_MD_FILE = DOCS_DIR / "FACTS.md"


def get_facts_path() -> Path:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    return FACTS_FILE


def load_all_facts() -> Dict[str, Dict[str, Any]]:
    """Load all registered facts from results/facts.json."""
    path = get_facts_path()
    if not path.exists():
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError:
        return {}


def register_fact(
    key: str,
    value: Any,
    unit: str = "",
    source_file: str = "",
    description: str = "",
) -> None:
    """Register or update a fact with its metadata."""
    facts = load_all_facts()
    facts[key] = {
        "value": value,
        "unit": unit,
        "source_file": source_file,
        "description": description,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }
    path = get_facts_path()
    with open(path, "w", encoding="utf-8") as f:
        json.dump(facts, f, indent=2, sort_keys=True)


def get_fact(key: str) -> Optional[Dict[str, Any]]:
    """Retrieve fact dictionary for a given key, or None if missing."""
    facts = load_all_facts()
    return facts.get(key)


def get_fact_value(key: str, default: Any = None) -> Any:
    """Retrieve value directly for a key."""
    fact = get_fact(key)
    if fact is None:
        return default
    return fact.get("value", default)


def generate_facts_markdown() -> str:
    """Generate docs/FACTS.md from all registered facts."""
    facts = load_all_facts()
    lines = [
        "# ChaosRL Facts Registry",
        "",
        "This document is auto-generated by `chaosrl.docs_tools.facts_registry`.",
        "It contains every verified number produced by experiment runs.",
        "",
        "| Key | Value | Unit | Source File | Timestamp |",
        "|---|---|---|---|---|",
    ]
    for key in sorted(facts.keys()):
        item = facts[key]
        val = item.get("value")
        # Format floats nicely if float
        if isinstance(val, float):
            val_str = f"{val:.4f}" if abs(val) < 1000 else f"{val:.2f}"
        else:
            val_str = str(val)
        unit_str = str(item.get("unit", ""))
        src_str = str(item.get("source_file", ""))
        ts_str = str(item.get("timestamp", ""))[:19]
        lines.append(f"| `{key}` | {val_str} | {unit_str} | `{src_str}` | {ts_str} |")

    lines.append("")
    content = "\n".join(lines)
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    with open(FACTS_MD_FILE, "w", encoding="utf-8") as f:
        f.write(content)
    return content

